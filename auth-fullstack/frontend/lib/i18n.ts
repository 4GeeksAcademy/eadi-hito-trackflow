export type Locale = 'es' | 'en';

export function localizedPath(path: string, locale: Locale): string {
  const withoutLocale = path.replace(/^\/en(?=\/|$)/, '') || '/';
  if (locale === 'es') return withoutLocale;
  return `/en${withoutLocale === '/' ? '' : withoutLocale}`;
}

